const SEP = " — ";

/** Bangla name for an English catalog name, or undefined when there is none. */
export function labelBn(en: string | undefined): string | undefined {
  if (!en) return undefined;
  const hit = BLOCK_LABELS_BN[en];
  if (hit) return hit;
  if (en.includes(SEP)) {
    const parts = en.split(SEP).map((p) => BLOCK_LABELS_BN[p.trim()]);
    if (parts.every(Boolean)) return parts.join(SEP);
  }
  return undefined;
}
